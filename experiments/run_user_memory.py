"""Run OmniMemEval's original user-memory pipelines through the HESM adapter.

Scoring, answer prompts, judge prompts and metric formulas remain in OmniMemEval.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

from experiments.settings import (
    ROOT,
    load_env,
    read_settings,
    validate_omnimemeval_models,
)


BENCHMARKS = {
    "locomo": {
        "folder": "locomo", "prefix": "locomo", "result_folder": "locomo",
        "stages": ["ingestion", "search", "responses", "eval", "metric", "report"],
        "primary_metric": "llm_as_judge_accuracy",
    },
    "lme": {
        "folder": "longmemeval", "prefix": "lme", "result_folder": "lme",
        "stages": ["ingestion", "search", "responses", "eval", "metric", "report"],
        "primary_metric": "llm_as_judge_accuracy",
    },
    "beam": {
        "folder": "beam", "prefix": "beam", "result_folder": "beam",
        "stages": ["ingestion", "search", "responses", "eval", "metric", "report"],
        "primary_metric": "nugget_score",
    },
}
BEAM_FILES = {
    "100k": "beam_100k.json", "500k": "beam_500k.json",
    "1m": "beam_1m.json", "10m": "beam_10m_10m.json",
}


def path_hash(path: str | Path) -> str:
    """Hash one file or a directory tree deterministically."""
    target = Path(path)
    sha = hashlib.sha256()
    files = [target] if target.is_file() else sorted(
        item for item in target.rglob("*") if item.is_file()
    )
    for item in files:
        label = item.name if target.is_file() else item.relative_to(target).as_posix()
        sha.update(label.encode("utf-8"))
        sha.update(b"\0")
        with item.open("rb") as handle:
            for block in iter(lambda: handle.read(1024 * 1024), b""):
                sha.update(block)
    return sha.hexdigest()


def combined_hash(paths: list[Path]) -> str:
    sha = hashlib.sha256()
    for path in paths:
        sha.update(path.name.encode("utf-8"))
        sha.update(path_hash(path).encode("ascii"))
    return sha.hexdigest()


def write(path: Path, value) -> None:
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def write_experiment_config(path: Path, args, version: str) -> None:
    """Write the non-secret parameter snapshot consumed by report scripts."""
    definition = BENCHMARKS[args.benchmark]
    values = {
        "LIB": "hesm", "VERSION": version,
        "WORKERS": args.workers, "LLM_WORKERS": args.llm_workers,
        "TOPK": args.top_k, "NUM_RUNS": args.judge_runs,
        "SAVE_MODEL_INPUT": 1, "ALLOW_EMPTY_SEARCH": 0,
        "SKIP_FAILED_SEARCH": 0, "SKIP_FAILED_ANSWER": 0,
        "SKIP_FAILED_JUDGE": 0, "CLEAR": 0, "NOTIFY": 0,
        "WAIT_AFTER_INGEST": 0,
        "PRIMARY_METRIC": definition["primary_metric"],
        "EFFICIENCY_METRIC": "average_answer_stage_context_tokens",
    }
    if args.benchmark == "beam":
        values["SCALE"] = args.scale
    lines = [
        "# Experiment configuration generated by HESM run_user_memory.py",
        "# Credentials are deliberately excluded.",
        f'RUN_TIMESTAMP="{time.strftime("%Y-%m-%d %H:%M:%S %z")}"',
        f'ENV_FILE_BASENAME="{Path(args.env).name}"',
    ]
    for key, value in values.items():
        escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key}="{escaped}"')
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def stage_commands(args, version: str) -> list[list[str]]:
    definition = BENCHMARKS[args.benchmark]
    commands = []
    for suffix in definition["stages"]:
        command = [
            str(args.eval_python),
            f'scripts/{definition["folder"]}/{definition["prefix"]}_{suffix}.py',
            "--lib", "hesm", "--version", version,
        ]
        if suffix in {"ingestion", "search"}:
            command += ["--workers", str(args.workers)]
        if suffix == "search":
            command += [
                "--top-k", str(args.top_k),
                "--allow-empty-search", "0",
                "--skip-failed-search", "0",
            ]
        if suffix == "responses":
            command += [
                "--llm-workers", str(args.llm_workers),
                "--save-model-input", "1",
                "--skip-failed-answer", "0",
            ]
        if suffix == "eval":
            command += [
                "--llm-workers", str(args.llm_workers),
                "--num_runs", str(args.judge_runs),
                "--skip-failed-judge", "0",
            ]
        if args.benchmark == "beam" and suffix in {"ingestion", "search"}:
            command += ["--scale", args.scale]
        commands.append(command)
    return commands


def resolve_dataset(args, repo: Path, parser) -> tuple[object, str, str, str]:
    """Return manifest path, data hash, env name and env value."""
    if args.benchmark == "locomo":
        path = (args.data or repo / "data/locomo/locomo10.json").resolve()
        required = [path]
        env_name, env_value = "OMNIMEMEVAL_LOCOMO_DATA", str(path)
        manifest_path: object = str(path)
    elif args.benchmark == "lme":
        path = (
            args.data
            or repo / "data/longmemeval/longmemeval_s_cleaned.json"
        ).resolve()
        required = [path]
        env_name, env_value = "OMNIMEMEVAL_LME_DATA", str(path)
        manifest_path = str(path)
    elif args.benchmark == "beam":
        root = (args.data or repo / "data/beam").resolve()
        path = root / BEAM_FILES[args.scale]
        required = [path]
        env_name, env_value = "OMNIMEMEVAL_BEAM_DATA_DIR", str(root)
        manifest_path = str(path)
    else:
        raise AssertionError(f"Unsupported benchmark: {args.benchmark}")

    missing = [str(path) for path in required if not path.exists()]
    if missing:
        parser.error(
            "Missing benchmark data:\n  " + "\n  ".join(missing)
            + "\nRun the corresponding OmniMemEval data preparation script first."
        )
    if any(path.is_dir() and not any(path.iterdir()) for path in required):
        parser.error("A required benchmark data directory is empty")
    digest = combined_hash(required)
    return manifest_path, digest, env_name, env_value


def service_health(settings, dataset_id: str):
    import requests

    session = requests.Session()
    session.trust_env = False
    response = session.get(
        os.environ["HESM_EVAL_URL"].rstrip("/") + "/health",
        headers={"Authorization": "Bearer " + os.environ["HESM_EVAL_TOKEN"]},
        timeout=2,
    )
    response.raise_for_status()
    health = response.json()
    if health.get("config_fingerprint") != settings["config_fingerprint"]:
        raise ValueError("A different HESM experiment service is using the configured URL")
    if health.get("dataset_id") != dataset_id:
        raise ValueError("A different dataset HESM service is using the configured URL")
    return health


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark", choices=list(BENCHMARKS), required=True)
    parser.add_argument("--scale", choices=list(BEAM_FILES), default="100k")
    parser.add_argument("--version", required=True)
    parser.add_argument(
        "--config", default=str(ROOT / "experiments/config/user_memory.yaml")
    )
    parser.add_argument(
        "--env", default=str(ROOT / "experiments/.env.user_memory")
    )
    parser.add_argument("--omnimemeval", type=Path, default=ROOT.parent / "OmniMemEval")
    parser.add_argument("--eval-python", type=Path, default=Path(sys.executable))
    parser.add_argument("--service-python", type=Path, default=Path(sys.executable))
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--llm-workers", type=int, default=2)
    parser.add_argument("--top-k", type=int, default=20)
    parser.add_argument("--judge-runs", type=int, default=1)
    parser.add_argument("--from-step", type=int, default=1)
    parser.add_argument("--to-step", type=int)
    parser.add_argument(
        "--data", type=Path,
        help="Explicit data file; BEAM expects a data directory.",
    )
    parser.add_argument(
        "--smoke", action="store_true",
        help="Mark custom/small data as a functional check, never a published result.",
    )
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--external-service", action="store_true")
    parser.add_argument(
        "--direct-network", action="store_true",
        help="Ignore inherited proxy variables.",
    )
    args = parser.parse_args()

    definition = BENCHMARKS[args.benchmark]
    stage_count = len(definition["stages"])
    if args.to_step is None:
        args.to_step = stage_count
    if not re.fullmatch(r"[A-Za-z0-9_-]+", args.version):
        parser.error("version must contain only letters, digits, underscore or hyphen")
    if min(args.workers, args.llm_workers, args.top_k, args.judge_runs) < 1:
        parser.error("Worker, top-k and run counts must be positive")
    if not 1 <= args.from_step <= args.to_step <= stage_count:
        parser.error(f"step range must be within 1..{stage_count}")

    load_env(args.env)
    validate_omnimemeval_models()
    settings = read_settings(args.config)
    client_host = settings["host"]
    if client_host in {"0.0.0.0", "::"}:
        client_host = "127.0.0.1"
    os.environ["HESM_EVAL_URL"] = f'http://{client_host}:{settings["port"]}'
    os.environ["HESM_EVAL_TOKEN"] = str(settings["api_token"])

    repo = args.omnimemeval.resolve(strict=True)
    suffix = args.benchmark
    if args.benchmark == "beam":
        suffix += f"_{args.scale}"
    version = f"{args.version}_{suffix}"
    if args.smoke:
        version = "smoke_" + version

    data_path, data_sha256, data_env_name, data_env_value = resolve_dataset(
        args, repo, parser
    )
    dataset_id = f"{version}_{data_sha256[:16]}"
    result_dir = (
        repo / "results" / definition["result_folder"] / f"hesm-{version}"
    )
    commands = stage_commands(args, version)
    manifest = {
        "status": "planned", "benchmark": args.benchmark, "version": version,
        "purpose": "functional_smoke" if args.smoke else "benchmark",
        "data_path": data_path, "data_sha256": data_sha256,
        "dataset_id": dataset_id,
        "config_fingerprint": settings["config_fingerprint"],
        "models": {
            "hesm": settings["native_models"],
            "answer": os.environ["ANSWER_MODEL"],
            "judge": os.environ["EVAL_MODEL"],
        },
        "primary_metric": definition["primary_metric"],
        "efficiency_metric": "average_answer_stage_context_tokens",
        "baseline_mode": "published_reference_only_no_baseline_runs",
        "commands": commands,
        "source_hashes": {
            str(Path(command[1])): path_hash(repo / command[1])
            for command in commands
        },
    }
    if args.dry_run:
        print(json.dumps(manifest, ensure_ascii=False, indent=2))
        return 0

    result_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = result_dir / "hesm_manifest.json"
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text(encoding="utf-8"))
        for key in (
            "data_sha256", "config_fingerprint", "models", "source_hashes",
            "commands", "purpose", "primary_metric", "efficiency_metric",
        ):
            if previous.get(key) != manifest[key]:
                raise ValueError(
                    f"Cannot resume changed experiment ({key}); choose a new version"
                )

    env = dict(os.environ)
    if args.direct_network:
        env["HESM_EVAL_DIRECT_NETWORK"] = "1"
        for key in (
            "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
            "http_proxy", "https_proxy", "all_proxy",
        ):
            env.pop(key, None)
    env.update({
        "OMNIMEMEVAL_ENV_FILE": str(Path(args.env).resolve()),
        "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8",
        "ANONYMIZED_TELEMETRY": "False",
        data_env_name: data_env_value,
        "HESM_EVAL_CONFIG_FINGERPRINT": settings["config_fingerprint"],
    })
    (result_dir / "snapshot_eval.env").write_text(
        "\n".join(
            f"{key}={env[key]}" for key in (
                "ANSWER_MODEL", "EVAL_MODEL", "HESM_EVAL_URL",
                "HESM_EVAL_CONFIG_FINGERPRINT",
            ) if key in env
        ) + "\n",
        encoding="utf-8",
    )
    write_experiment_config(result_dir / "experiment_config.sh", args, version)
    public_settings = {
        key: value for key, value in settings.items()
        if key not in {"api_token", "native_config"}
    }
    (result_dir / "hesm_config_snapshot.json").write_text(
        json.dumps(public_settings, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    stage_log = result_dir / "hesm_execution.json"
    progress = (
        json.loads(stage_log.read_text(encoding="utf-8"))
        if stage_log.exists() else []
    )
    process, service_log = None, None
    try:
        if args.from_step <= 2:
            try:
                service_health(settings, dataset_id)
            except ValueError:
                raise
            except Exception:
                if args.external_service:
                    raise
                service_log = (result_dir / "hesm_service.log").open(
                    "a", encoding="utf-8"
                )
                process = subprocess.Popen(
                    [
                        str(args.service_python), "-B", "-m", "experiments.server",
                        "--config", str(Path(args.config).resolve()),
                        "--env", str(Path(args.env).resolve()),
                        "--dataset-id", dataset_id,
                    ],
                    cwd=ROOT, env=env, stdout=service_log,
                    stderr=subprocess.STDOUT,
                    creationflags=(
                        subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0
                    ),
                )
                deadline = time.monotonic() + 60
                while True:
                    if process.poll() is not None:
                        raise RuntimeError(
                            f'HESM service exited; see {result_dir / "hesm_service.log"}'
                        )
                    try:
                        service_health(settings, dataset_id)
                        break
                    except Exception:
                        if time.monotonic() > deadline:
                            raise RuntimeError("HESM service startup timeout")
                        time.sleep(0.5)

        manifest["status"] = "running"
        write(manifest_path, manifest)
        for step in range(args.from_step, args.to_step + 1):
            command = commands[step - 1]
            print(f'[{step}/{stage_count}] {Path(command[1]).name}', flush=True)
            started = time.time()
            log_path = result_dir / f"hesm_step_{step}.log"
            with log_path.open("a", encoding="utf-8") as log:
                completed = subprocess.run(
                    command, cwd=repo, env=env,
                    stdout=log, stderr=subprocess.STDOUT,
                )
            progress.append({
                "step": step, "exit_code": completed.returncode,
                "elapsed_seconds": time.time() - started,
                "log": str(log_path),
            })
            write(stage_log, progress)
            if completed.returncode:
                manifest["status"] = "failed"
                manifest["failed_step"] = step
                write(manifest_path, manifest)
                print(f"Failed; inspect {log_path}", flush=True)
                return completed.returncode

        latest = {item["step"]: item["exit_code"] for item in progress}
        passed = {step for step, code in latest.items() if code == 0}
        expected = set(range(1, stage_count + 1))
        manifest["status"] = "complete" if passed == expected else "partial"
        write(manifest_path, manifest)
        print(f'{manifest["status"]}: {result_dir}', flush=True)
        return 0
    finally:
        if process is not None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
        if service_log is not None:
            service_log.close()


if __name__ == "__main__":
    raise SystemExit(main())
