"""Cross-platform launcher of OmniMemEval's original six evaluation stages.

No scoring, answer prompts, or baseline execution is reimplemented here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

from experiments.settings import ROOT, read_settings, load_env

SCRIPTS = {
    'locomo': ('locomo', 'locomo', ['ingestion', 'search', 'responses', 'eval', 'metric', 'report']),
    'lme': ('longmemeval', 'lme', ['ingestion', 'search', 'responses', 'eval', 'metric', 'report']),
    'beam': ('beam', 'beam', ['ingestion', 'search', 'responses', 'eval', 'metric', 'report']),
}
BEAM_FILES = {'100k': 'beam_100k.json', '500k': 'beam_500k.json', '1m': 'beam_1m.json', '10m': 'beam_10m_10m.json'}


def file_hash(path):
    sha = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            sha.update(block)
    return sha.hexdigest()


def write(path, value):
    tmp = path.with_suffix('.tmp')
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
    tmp.replace(path)


def write_experiment_config(path, args, version):
    """Write the parameter snapshot consumed by OmniMemEval report scripts."""
    values = {
        'LIB': 'hesm',
        'VERSION': version,
        'WORKERS': args.workers,
        'LLM_WORKERS': args.llm_workers,
        'TOPK': args.top_k,
        'NUM_RUNS': args.judge_runs,
        'SAVE_MODEL_INPUT': 1,
        'ALLOW_EMPTY_SEARCH': 0,
        'SKIP_FAILED_SEARCH': 0,
        'SKIP_FAILED_ANSWER': 0,
        'SKIP_FAILED_JUDGE': 0,
        'CLEAR': 0,
        'NOTIFY': 0,
        'WAIT_AFTER_INGEST': 0,
    }
    if args.benchmark == 'beam':
        values.update({
            'SCALE': args.scale,
            'SKIP_FAILED_STREAMING': 0,
            'STREAMING': 0,
            'START_IDX': 0,
            'END_IDX': '',
            'RESTART_UNIT': 0,
            'NO_RESUME': 0,
        })
    lines = [
        '# Experiment configuration - generated by HESM run_user_memory.py',
        '# Credentials are deliberately excluded.',
        f'RUN_TIMESTAMP="{time.strftime("%Y-%m-%d %H:%M:%S %z")}"',
        f'ENV_FILE_BASENAME="{Path(args.env).name}"',
    ]
    for key, value in values.items():
        escaped = str(value).replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'{key}="{escaped}"')
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def stage_commands(args, version):
    folder, prefix, stages = SCRIPTS[args.benchmark]
    commands = []
    for step, suffix in enumerate(stages, 1):
        command = [str(args.eval_python), f'scripts/{folder}/{prefix}_{suffix}.py', '--lib', 'hesm', '--version', version]
        if step in [1, 2]:
            command += ['--workers', str(args.workers)]
            if args.benchmark == 'beam':
                command += ['--scale', args.scale]
        if step == 2:
            command += ['--top-k', str(args.top_k)]
        if step in [3, 4]:
            command += ['--llm-workers', str(args.llm_workers)]
        if step == 3:
            command += ['--save-model-input', '1']
        if step == 4:
            command += ['--num_runs', str(args.judge_runs)]
        commands.append(command)
    return commands


def service_health(settings):
    import requests
    session = requests.Session()
    session.trust_env = False
    response = session.get(os.environ['HESM_EVAL_URL'].rstrip('/') + '/health',
        headers={'Authorization': 'Bearer ' + os.environ['HESM_EVAL_TOKEN']}, timeout=2)
    response.raise_for_status()
    health = response.json()
    if health.get('config_fingerprint') != settings['config_fingerprint']:
        raise ValueError('A different HESM experiment service is using the configured URL')
    return health


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--benchmark', choices=list(SCRIPTS), required=True)
    parser.add_argument('--scale', choices=list(BEAM_FILES), default='100k')
    parser.add_argument('--version', required=True)
    parser.add_argument('--config', default=str(ROOT / 'experiments/config/user_memory.yaml'))
    parser.add_argument('--env', default=str(ROOT / 'experiments/.env.user_memory'))
    parser.add_argument('--omnimemeval', type=Path, default=ROOT.parent / 'OmniMemEval')
    parser.add_argument('--eval-python', type=Path, default=Path(sys.executable))
    parser.add_argument('--service-python', type=Path, default=Path(sys.executable))
    parser.add_argument('--workers', type=int, default=1)
    parser.add_argument('--llm-workers', type=int, default=2)
    parser.add_argument('--top-k', type=int, default=20)
    parser.add_argument('--judge-runs', type=int, default=1)
    parser.add_argument('--from-step', type=int, choices=range(1, 7), default=1)
    parser.add_argument('--to-step', type=int, choices=range(1, 7), default=6)
    parser.add_argument('--data', type=Path, help='Explicit data file (BEAM: directory). No source data is overwritten.')
    parser.add_argument('--smoke', action='store_true', help='Mark a small/custom dataset as a functional check, never a published benchmark result')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--external-service', action='store_true')
    parser.add_argument('--direct-network', action='store_true', help='Ignore inherited proxies; requires network authorization in sandboxed environments')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9_-]+', args.version):
        parser.error('version must contain only letters, digits, underscore or hyphen')
    if min(args.workers, args.llm_workers, args.top_k, args.judge_runs) < 1 or args.from_step > args.to_step:
        parser.error('Invalid count or step range')
    load_env(args.env)
    settings = read_settings(args.config)
    repo = args.omnimemeval.resolve(strict=True)
    version = f'{args.version}_{args.benchmark}' + (f'_{args.scale}' if args.benchmark == 'beam' else '')
    if args.smoke:
        version = 'smoke_' + version
    data_env = {'locomo': 'OMNIMEMEVAL_LOCOMO_DATA', 'lme': 'OMNIMEMEVAL_LME_DATA', 'beam': 'OMNIMEMEVAL_BEAM_DATA_DIR'}
    default_data = {'locomo': repo / 'data/locomo/locomo10.json', 'lme': repo / 'data/longmemeval/longmemeval_s_cleaned.json', 'beam': repo / 'data/beam'}
    data = (args.data or default_data[args.benchmark]).resolve()
    data_file = data / BEAM_FILES[args.scale] if args.benchmark == 'beam' else data
    if not data_file.is_file():
        parser.error(f'Missing dataset: {data_file}; run the original OmniMemEval data preparation script first')
    result_dir = repo / 'results' / args.benchmark / f'hesm-{version}'
    commands = stage_commands(args, version)
    manifest = {'status': 'planned', 'benchmark': args.benchmark, 'version': version,
                'purpose': 'functional_smoke' if args.smoke else 'benchmark',
                'data_path': str(data_file), 'data_sha256': file_hash(data_file),
                'config_fingerprint': settings['config_fingerprint'],
                'models': {key: os.environ.get(key) for key in ['ANSWER_MODEL', 'EVAL_MODEL']},
                'memory_model': settings['models']['memory']['model'],
                'embedding_model': settings['models']['embedding']['model'],
                'baseline_mode': 'published_reference_only_no_baseline_runs',
                'commands': commands,
                'source_hashes': {str(Path(c[1])): file_hash(repo / c[1]) for c in commands}}
    if args.dry_run:
        print(json.dumps(manifest, ensure_ascii=False, indent=2))
        return 0
    result_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = result_dir / 'hesm_manifest.json'
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text(encoding='utf-8'))
        for key in ['data_sha256', 'config_fingerprint', 'models', 'source_hashes', 'commands', 'purpose']:
            if previous.get(key) != manifest[key]:
                raise ValueError(f'Cannot resume changed experiment ({key}); choose a new version')
    env = dict(os.environ)
    if args.direct_network:
        env['HESM_EVAL_DIRECT_NETWORK'] = '1'
        for key in ['HTTP_PROXY', 'HTTPS_PROXY', 'ALL_PROXY', 'http_proxy', 'https_proxy', 'all_proxy']:
            env.pop(key, None)
    env.update({'OMNIMEMEVAL_ENV_FILE': str(Path(args.env).resolve()), 'PYTHONUTF8': '1',
                'PYTHONIOENCODING': 'utf-8', 'ANONYMIZED_TELEMETRY': 'False',
                data_env[args.benchmark]: str(data),
                'HESM_EVAL_CONFIG_FINGERPRINT': settings['config_fingerprint']})
    # Reports use the same environment snapshot convention, with an allowlist
    # that excludes all credential variables instead of trying to redact text.
    (result_dir / 'snapshot_eval.env').write_text('\n'.join(f'{k}={env[k]}' for k in [
        'ANSWER_MODEL', 'EVAL_MODEL', 'HESM_EVAL_URL', 'HESM_EVAL_CONFIG_FINGERPRINT'] if k in env) + '\n', encoding='utf-8')
    write_experiment_config(result_dir / 'experiment_config.sh', args, version)
    (result_dir / 'hesm_config_snapshot.json').write_text(json.dumps(settings, ensure_ascii=False, indent=2), encoding='utf-8')
    stage_log = result_dir / 'hesm_execution.json'
    progress = json.loads(stage_log.read_text(encoding='utf-8')) if stage_log.exists() else []
    process, service_log = None, None
    try:
        if args.from_step <= 2:
            try:
                service_health(settings)
            except ValueError:
                raise
            except Exception:
                if args.external_service:
                    raise
                service_log = (result_dir / 'hesm_service.log').open('a', encoding='utf-8')
                process = subprocess.Popen([str(args.service_python), '-B', '-m', 'experiments.server',
                    '--config', str(Path(args.config).resolve()), '--env', str(Path(args.env).resolve())],
                    cwd=ROOT, env=env, stdout=service_log, stderr=subprocess.STDOUT,
                    creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0)
                deadline = time.monotonic() + 60
                while True:
                    if process.poll() is not None:
                        raise RuntimeError(f'HESM service exited; see {result_dir / "hesm_service.log"}')
                    try:
                        service_health(settings)
                        break
                    except Exception:
                        if time.monotonic() > deadline:
                            raise RuntimeError('HESM service startup timeout')
                        time.sleep(.5)
        manifest['status'] = 'running'
        write(manifest_path, manifest)
        for step in range(args.from_step, args.to_step + 1):
            command = commands[step - 1]
            print(f'[{step}/6] {Path(command[1]).name}', flush=True)
            started = time.time()
            log_path = result_dir / f'hesm_step_{step}.log'
            with log_path.open('a', encoding='utf-8') as log:
                completed = subprocess.run(command, cwd=repo, env=env, stdout=log, stderr=subprocess.STDOUT)
            progress.append({'step': step, 'exit_code': completed.returncode, 'elapsed_seconds': time.time() - started,
                             'log': str(log_path)})
            write(stage_log, progress)
            if completed.returncode:
                manifest['status'] = 'failed'
                manifest['failed_step'] = step
                write(manifest_path, manifest)
                print(f'Failed; inspect {log_path}', flush=True)
                return completed.returncode
        latest = {p['step']: p['exit_code'] for p in progress}
        passed = {step for step, code in latest.items() if code == 0}
        manifest['status'] = 'complete' if passed == set(range(1, 7)) else 'partial'
        write(manifest_path, manifest)
        print(f'{manifest["status"]}: {result_dir}', flush=True)
        return 0
    finally:
        if process is not None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
        if service_log is not None:
            service_log.close()


if __name__ == '__main__':
    raise SystemExit(main())
